@Composable
fun MyApplicationTheme(
    themeMode: String = "SYSTEM",
    themePreset: String = "OCEAN",
    fontScale: Float = 1.0f,
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val systemDark = isSystemInDarkTheme()
    val isDark = when (themeMode) {
        "DARK" -> true
        "LIGHT" -> false
        else -> systemDark
    }

    val preset = ThemePresets.getPreset(themePreset)

    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (isDark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        isDark -> preset.darkColors
        else -> preset.lightColors
    }

    val currentDensity = LocalDensity.current
    // Guard against layout breakage and vertical button squishing while ensuring great accessibility
    val safeEffectiveFontScale = (currentDensity.fontScale * fontScale).coerceIn(0.85f, 1.85f)
    val customDensity = Density(
        density = currentDensity.density,
        fontScale = safeEffectiveFontScale
    )

    CompositionLocalProvider(LocalDensity provides customDensity) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}
